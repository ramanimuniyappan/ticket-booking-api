CREATE TABLE roles
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_role_name
        CHECK (name IN ('CUSTOMER', 'ORGANIZER', 'ADMIN'))
);


CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_users_email UNIQUE (email)
);


CREATE TABLE user_roles
(
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,

    PRIMARY KEY (user_id, role_id),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id)
            REFERENCES users (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id)
            REFERENCES roles (id)
            ON DELETE RESTRICT
);

CREATE INDEX idx_user_roles_role_id
    ON user_roles (role_id);


CREATE TABLE venues
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name       VARCHAR(150) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    address    TEXT         NOT NULL,
    capacity   INTEGER      NOT NULL,

    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_venue_capacity
        CHECK (capacity > 0),

    CONSTRAINT chk_venue_name
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_venue_city
        CHECK (LENGTH(TRIM(city)) > 0),

    CONSTRAINT chk_venue_address
        CHECK (LENGTH(TRIM(address)) > 0)
);


CREATE TABLE seats
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    venue_id    BIGINT      NOT NULL,
    section     VARCHAR(30) NOT NULL,
    row_label   VARCHAR(10) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    category    VARCHAR(30) NOT NULL,

    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_seats_venue
        FOREIGN KEY (venue_id)
            REFERENCES venues (id)
            ON DELETE RESTRICT,

    CONSTRAINT uq_seat_location
        UNIQUE (
                venue_id,
                section,
                row_label,
                seat_number
            ),

    CONSTRAINT chk_seat_section
        CHECK (LENGTH(TRIM(section)) > 0),

    CONSTRAINT chk_seat_row
        CHECK (LENGTH(TRIM(row_label)) > 0),

    CONSTRAINT chk_seat_number
        CHECK (LENGTH(TRIM(seat_number)) > 0),

    CONSTRAINT chk_seat_category
        CHECK (category IN ('REGULAR', 'PREMIUM', 'VIP'))
);

CREATE INDEX idx_seats_venue_id
    ON seats (venue_id);


CREATE TABLE events
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    title        VARCHAR(200) NOT NULL,
    description  TEXT,
    category     VARCHAR(50)  NOT NULL,
    organizer_id BIGINT       NOT NULL,
    status       VARCHAR(30)  NOT NULL DEFAULT 'DRAFT',

    created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_events_organizer
        FOREIGN KEY (organizer_id)
            REFERENCES users (id)
            ON DELETE RESTRICT,

    CONSTRAINT chk_event_title
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT chk_event_category
        CHECK (category IN (
                            'CONCERT',
                            'SPORTS',
                            'COMEDY',
                            'THEATRE',
                            'CONFERENCE'
            )),

    CONSTRAINT chk_event_status
        CHECK (status IN (
                          'DRAFT',
                          'PUBLISHED',
                          'CANCELLED',
                          'COMPLETED'
            ))
);

CREATE INDEX idx_events_organizer_id
    ON events (organizer_id);


CREATE TABLE event_shows
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id   BIGINT      NOT NULL,
    venue_id   BIGINT      NOT NULL,

    start_time TIMESTAMPTZ NOT NULL,
    end_time   TIMESTAMPTZ NOT NULL,

    status     VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_event_shows_event
        FOREIGN KEY (event_id)
            REFERENCES events (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_event_shows_venue
        FOREIGN KEY (venue_id)
            REFERENCES venues (id)
            ON DELETE RESTRICT,

    CONSTRAINT chk_show_time
        CHECK (end_time > start_time),

    CONSTRAINT chk_show_status
        CHECK (status IN (
                          'SCHEDULED',
                          'ONGOING',
                          'COMPLETED',
                          'CANCELLED'
            ))
);

CREATE INDEX idx_event_shows_event_id
    ON event_shows (event_id);

CREATE INDEX idx_event_shows_venue_id
    ON event_shows (venue_id);


CREATE TABLE show_seats
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    show_id    BIGINT         NOT NULL,
    seat_id    BIGINT         NOT NULL,

    price      NUMERIC(10, 2) NOT NULL,
    status     VARCHAR(20)    NOT NULL DEFAULT 'AVAILABLE',

    held_by    BIGINT,
    hold_token UUID,
    held_until TIMESTAMPTZ,

    version    BIGINT         NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_show_seats_show
        FOREIGN KEY (show_id)
            REFERENCES event_shows (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_show_seats_seat
        FOREIGN KEY (seat_id)
            REFERENCES seats (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_show_seats_held_by
        FOREIGN KEY (held_by)
            REFERENCES users (id)
            ON DELETE RESTRICT,

    CONSTRAINT uq_show_seat
        UNIQUE (show_id, seat_id),

    CONSTRAINT chk_show_seat_price
        CHECK (price >= 0),

    CONSTRAINT chk_show_seat_version
        CHECK (version >= 0),

    CONSTRAINT chk_show_seat_status
        CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED')),

    CONSTRAINT chk_show_seat_hold
        CHECK (
            (
                status = 'HELD'
                    AND held_by IS NOT NULL
                    AND hold_token IS NOT NULL
                    AND held_until IS NOT NULL
                )
                OR
            (
                status IN ('AVAILABLE', 'BOOKED')
                    AND held_by IS NULL
                    AND hold_token IS NULL
                    AND held_until IS NULL
                )
            )
);

CREATE INDEX idx_show_seats_show_status
    ON show_seats (show_id, status);

CREATE INDEX idx_show_seats_held_until
    ON show_seats (held_until)
    WHERE status = 'HELD';


CREATE TABLE bookings
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id      BIGINT         NOT NULL,
    show_id      BIGINT         NOT NULL,

    status       VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    total_amount NUMERIC(12, 2) NOT NULL,

    expires_at   TIMESTAMPTZ,

    created_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_bookings_user
        FOREIGN KEY (user_id)
            REFERENCES users (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_bookings_show
        FOREIGN KEY (show_id)
            REFERENCES event_shows (id)
            ON DELETE RESTRICT,

    CONSTRAINT chk_booking_status
        CHECK (status IN (
                          'PENDING',
                          'CONFIRMED',
                          'EXPIRED',
                          'CANCELLED'
            )),

    CONSTRAINT chk_booking_amount
        CHECK (total_amount >= 0),

    CONSTRAINT chk_booking_expiry
        CHECK (
            status <> 'PENDING'
                OR expires_at IS NOT NULL
            )
);

CREATE INDEX idx_bookings_user_id
    ON bookings (user_id);

CREATE INDEX idx_bookings_show_id
    ON bookings (show_id);

CREATE INDEX idx_bookings_pending_expiry
    ON bookings (expires_at)
    WHERE status = 'PENDING';


CREATE TABLE tickets
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id    BIGINT         NOT NULL,
    show_seat_id  BIGINT         NOT NULL,

    ticket_number VARCHAR(100)   NOT NULL,
    price_paid    NUMERIC(10, 2) NOT NULL,

    status        VARCHAR(20)    NOT NULL DEFAULT 'ACTIVE',

    created_at    TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_tickets_booking
        FOREIGN KEY (booking_id)
            REFERENCES bookings (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_tickets_show_seat
        FOREIGN KEY (show_seat_id)
            REFERENCES show_seats (id)
            ON DELETE RESTRICT,

    CONSTRAINT uq_ticket_number
        UNIQUE (ticket_number),

    CONSTRAINT chk_ticket_price
        CHECK (price_paid >= 0),

    CONSTRAINT chk_ticket_status
        CHECK (status IN (
                          'ACTIVE',
                          'CANCELLED',
                          'USED'
            ))
);

CREATE UNIQUE INDEX uq_active_ticket_per_seat
    ON tickets (show_seat_id)
    WHERE status IN ('ACTIVE', 'USED');

CREATE INDEX idx_tickets_booking_id
    ON tickets (booking_id);


CREATE TABLE payments
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id          BIGINT         NOT NULL,

    amount              NUMERIC(12, 2) NOT NULL,
    currency            CHAR(3)        NOT NULL DEFAULT 'INR',

    payment_method      VARCHAR(30),
    provider            VARCHAR(50)    NOT NULL,

    provider_payment_id VARCHAR(150),
    idempotency_key     UUID           NOT NULL,

    status              VARCHAR(30)    NOT NULL DEFAULT 'PENDING',

    created_at          TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_payments_booking
        FOREIGN KEY (booking_id)
            REFERENCES bookings (id)
            ON DELETE RESTRICT,

    CONSTRAINT uq_payment_idempotency
        UNIQUE (idempotency_key),

    CONSTRAINT chk_payment_amount
        CHECK (amount > 0),

    CONSTRAINT chk_payment_currency
        CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_payment_status
        CHECK (status IN (
                          'PENDING',
                          'SUCCESS',
                          'FAILED',
                          'REFUNDED'
            ))
);

CREATE UNIQUE INDEX uq_provider_payment
    ON payments (provider, provider_payment_id)
    WHERE provider_payment_id IS NOT NULL;

CREATE INDEX idx_payments_booking_id
    ON payments (booking_id);


